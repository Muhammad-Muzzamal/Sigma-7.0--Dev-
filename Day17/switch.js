let color = "green";

switch (color) {
  case "red":
    console.log("Stop the car\n");
    break;
  case "yellow":
    console.log("Ready to go\n");
    break;
  case "green":
    console.log("You can go\n");
    break;
  default:
    console.log("Break the signal");
    break;
}
